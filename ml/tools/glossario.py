def nome(acao: str) -> str:
    for s in SUFIXOS:
        if acao.endswith(s):
            return acao[: -len(s)]
    return acao


def linhas(acoes: set[str]) -> str:
    """O bloco do glossário para as ações de uma luta, ordenado, sem repetir."""
    vistos = sorted({nome(a) for a in acoes if nome(a) in G})
    if not vistos:
        return ""
    return "=== O QUE CADA HABILIDADE FAZ (WotLK 3.3.5) ===\n" + "\n".join(f"- {a}: {G[a]}" for a in vistos)


def selftest() -> None:
    assert nome("wind shear on enemy healer") == "wind shear" and nome("purge") == "purge"
    t = linhas({"victory rush", "riptide on party", "xyz"})
    assert "victory rush: " in t and "não é cooldown" in t and "riptide: " in t and "xyz" not in t
    assert linhas({"xyz"}) == ""
    print(f"ok glossario ({len(G)} habilidades)")


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        selftest()
